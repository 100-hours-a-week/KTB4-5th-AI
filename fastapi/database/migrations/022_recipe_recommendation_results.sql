-- 레시피 작업의 완료/실패 snapshot 보관. 접수 대기 큐는 이 테이블에 저장하지 않는다.
BEGIN;
CREATE SCHEMA IF NOT EXISTS recipe_ai;
CREATE TABLE IF NOT EXISTS recipe_ai.recommendation_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id TEXT NOT NULL UNIQUE,
    request_id TEXT NOT NULL UNIQUE,
    request_hash TEXT NOT NULL CHECK (length(request_hash) = 64),
    snapshot JSONB NOT NULL CHECK ((snapshot->>'status' IN ('COMPLETED','FAILED')) IS TRUE),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE recipe_ai.recommendation_results IS '레시피 작업 최종 결과/재조회 이력. 사용자 재고 차감이나 학습 데이터가 아님';
COMMIT;
