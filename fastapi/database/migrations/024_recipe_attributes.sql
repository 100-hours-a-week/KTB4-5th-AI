-- 승인된 레시피의 원문 / 모델 버전별 AI 요리 성격 분류. 사용자 취향이나 날씨와 무관한 원천 속성이다.
BEGIN;
CREATE TABLE IF NOT EXISTS recipe_ai.recipe_attributes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL REFERENCES recipe_ai.recipes(id) ON DELETE CASCADE,
    attribute_key TEXT NOT NULL UNIQUE CHECK (length(attribute_key)=64),
    model_name TEXT NOT NULL,
    prompt_version TEXT NOT NULL,
    attribute_version TEXT NOT NULL,
    attributes JSONB NOT NULL CHECK (jsonb_typeof(attributes)='object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS recipe_attributes_recipe_id_idx ON recipe_ai.recipe_attributes(recipe_id);
COMMENT ON TABLE recipe_ai.recipe_attributes IS 'AI가 추정한 요리 종류 / 형태 / 온도 / 무게감 / 난이도 / 식사 목적 / 식감. UNKNOWN은 미확정이며 정답 라벨이 아님';
-- dev 앱 계정은 CREATE 권한이 없어 소유자 계정으로 실행해야 한다.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='receipt_ai') THEN
        GRANT USAGE ON SCHEMA recipe_ai TO receipt_ai;
        GRANT SELECT,INSERT,UPDATE ON recipe_ai.recipe_attributes TO receipt_ai;
        GRANT USAGE,SELECT ON SEQUENCE recipe_ai.recipe_attributes_id_seq TO receipt_ai;
    END IF;
END $$;
COMMIT;
