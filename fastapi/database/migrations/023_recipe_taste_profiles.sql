-- 승인된 레시피의 원문 / 모델 버전별 AI 맛 평가. 실제 관능평가나 사용자 프로필이 아니다.
BEGIN;
CREATE TABLE IF NOT EXISTS recipe_ai.taste_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL REFERENCES recipe_ai.recipes(id) ON DELETE CASCADE,
    profile_key TEXT NOT NULL UNIQUE CHECK (length(profile_key)=64),
    model_name TEXT NOT NULL,
    prompt_version TEXT NOT NULL,
    evaluation_version TEXT NOT NULL,
    profile JSONB NOT NULL CHECK (jsonb_typeof(profile)='object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE recipe_ai.taste_profiles IS '원문 근거를 검증한 AI 추정 맛 특성. UNKNOWN은 미확정, 사용자 취향 및 관능평가 정답이 아님';
-- dev 앱 계정은 CREATE 권한이 없어 소유자 계정으로 실행해야 한다.
-- 다른 환경의 앱 역할 이름이 다르면 해당 역할에도 동일한 최소 권한을 별도로 부여한다.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='receipt_ai') THEN
        GRANT USAGE ON SCHEMA recipe_ai TO receipt_ai;
        GRANT SELECT,INSERT,UPDATE ON recipe_ai.taste_profiles TO receipt_ai;
        GRANT USAGE,SELECT ON SEQUENCE recipe_ai.taste_profiles_id_seq TO receipt_ai;
    END IF;
END $$;
COMMIT;
